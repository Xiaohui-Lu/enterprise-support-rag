"""Retrieval reports: summary tables and paired comparisons from run records.

Runs are git-ignored (D-018); the report names every run ID and git commit it came from,
so each number traces back to a reproducible command. Comparisons follow D-036: real
questions decide, by recall@10, and a change counts only if its paired 95% interval lies
entirely above zero.
"""

from __future__ import annotations

from collections.abc import Callable, Sequence
from itertools import combinations
from pathlib import Path
from statistics import fmean
from typing import Any

from support_rag import config
from support_rag.retrieval_eval import format_summary
from support_rag.runs import load_config, load_results, load_summary
from support_rag.stats import paired_bootstrap_ci, sign_test

DECIDING_GROUP, DECIDING_METRIC = "real", "recall@10"  # D-036
COMPARED_METRICS = ("recall@10", "all_gold@10", "recall@5", "mrr@20")

Result = dict[str, Any]

# Real and synthetic questions behave differently (D-015), so they're never pooled.
_GROUPS: dict[str, Callable[[Result], bool]] = {
    "real": lambda r: r["subset"] != "synthetic",
    "synthetic": lambda r: r["subset"] == "synthetic",
}


def report_path(name: str) -> Path:
    return config.REPORTS_DIR / f"retrieval_{name}.md"


def paired_scores(
    base: Sequence[Result], other: Sequence[Result], metric: str
) -> tuple[list[float], list[float]]:
    """Both runs' scores on each question, in the base run's order. Raises ValueError if
    the runs don't cover the same questions."""
    other_by_id = {r["question_id"]: r["metrics"][metric] for r in other}
    if other_by_id.keys() != {r["question_id"] for r in base}:
        raise ValueError("the runs don't cover the same questions")
    return [r["metrics"][metric] for r in base], [other_by_id[r["question_id"]] for r in base]


def paired_changes(base: Sequence[Result], other: Sequence[Result], metric: str) -> dict[str, int]:
    """Question by question: how often `other` scored higher, lower or the same as `base`."""
    before, after = paired_scores(base, other, metric)
    pairs = list(zip(before, after, strict=True))
    return {
        "better": sum(a > b for b, a in pairs),
        "worse": sum(a < b for b, a in pairs),
        "same": sum(a == b for b, a in pairs),
    }


def verdict(low: float, high: float) -> str:
    """D-036: a difference counts only if its paired 95% interval excludes zero."""
    if low > 0:
        return "clearly better"
    if high < 0:
        return "clearly worse"
    return "within noise"


def describe(run_config: dict[str, Any]) -> str:
    """One line for the runs table: which retriever, with its main settings."""
    retriever = run_config.get("retriever", {})
    if retriever.get("name") == "dense":
        return f"dense: {retriever['model']}, {retriever['dimensions']} dims, {retriever['dtype']}"
    if retriever.get("name") == "bm25":
        stem = run_config.get("tokenizer", {}).get("stem")
        return f"BM25, stemming {'on' if stem else 'off'}"
    return str(retriever.get("name", "unknown"))


def write_report(run_dirs: Sequence[Path], *, name: str, path: Path | None = None) -> Path:
    """Each run is compared with every earlier run on the same split."""
    path = path or report_path(name)
    configs = [load_config(d) for d in run_dirs]
    lines = [
        f"# Retrieval: {name}",
        "",
        "Generated by `srag report-retrieval` from the run records below (D-018). Runs are",
        "git-ignored; each can be reproduced with `srag eval-retrieval` at its commit.",
        "",
        "## Runs",
        "",
        "| Run | Retriever | Split | Questions | Commit | Uncommitted changes |",
        "|---|---|---|---:|---|---|",
    ]
    for c in configs:
        commit = (c["git"]["commit"] or "unknown")[:7]
        lines.append(
            f"| `{c['run_id']}` | {describe(c)} | {c['split']} | {c['n_questions']} | "
            f"`{commit}` | {'yes' if c['git']['dirty'] else 'no'} |"
        )
    for run_dir, c in zip(run_dirs, configs, strict=True):
        lines += ["", f"## `{c['run_id']}`", "", format_summary(load_summary(run_dir))]

    pairs = [
        (i, j)
        for i, j in combinations(range(len(run_dirs)), 2)
        if configs[i]["split"] == configs[j]["split"]
    ]
    if pairs:
        lines += [
            "",
            "## Paired comparisons",
            "",
            "Same questions in both runs. Difference is the later run minus the earlier one,",
            "with a paired 95% bootstrap interval over questions (D-032). Better / worse / same",
            "count the questions where the later run scored higher, lower or equal, and p is",
            "the two-sided sign test on better vs worse. Under D-036, real questions decide by",
            "recall@10, and a change counts only if its interval is entirely above zero.",
        ]
    results = [load_results(d) for d in run_dirs]
    for i, j in pairs:
        lines += _comparison(configs[i], results[i], configs[j], results[j])

    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return path


def _comparison(
    base_config: dict[str, Any],
    base_results: Sequence[Result],
    other_config: dict[str, Any],
    other_results: Sequence[Result],
) -> list[str]:
    lines = [
        "",
        f"### `{other_config['run_id']}` vs `{base_config['run_id']}`",
        "",
        "| Group | Metric | Earlier | Later | Difference [95% CI] | Better | Worse | Same | p |",
        "|---|---|---:|---:|---|---:|---:|---:|---:|",
    ]
    decision = None
    for group, keep in _GROUPS.items():
        base = [r for r in base_results if keep(r)]
        other = [r for r in other_results if keep(r)]
        if not base:
            continue
        for metric in COMPARED_METRICS:
            before, after = paired_scores(base, other, metric)
            low, high = paired_bootstrap_ci(after, before)
            difference = fmean(after) - fmean(before)
            n = paired_changes(base, other, metric)
            p = sign_test(n["better"], n["worse"])
            lines.append(
                f"| {group} | {metric} | {fmean(before):.3f} | {fmean(after):.3f} | "
                f"{difference:+.3f} [{low:+.3f}, {high:+.3f}] | {n['better']} | {n['worse']} | "
                f"{n['same']} | {'<0.001' if p < 0.001 else f'{p:.3f}'} |"
            )
            if (group, metric) == (DECIDING_GROUP, DECIDING_METRIC):
                decision = (
                    f"D-036 ({group} questions, {metric}): {difference:+.3f} "
                    f"[{low:+.3f}, {high:+.3f}], **{verdict(low, high)}**."
                )
    if decision:
        lines += ["", decision]
    return lines
