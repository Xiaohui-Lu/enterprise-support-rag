"""The committed retrieval report: summary tables and paired comparisons from run records.

Runs are git-ignored (D-018); the report names every run ID and git commit it came from,
so each number traces back to a reproducible command.
"""

from __future__ import annotations

from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Any

from support_rag import config
from support_rag.retrieval_eval import format_summary
from support_rag.runs import load_config, load_results, load_summary

REPORT_PATH = config.REPORTS_DIR / "retrieval_bm25.md"
COMPARED_METRICS = ("recall@5", "mrr@20")

Result = dict[str, Any]

# Groups for paired comparisons. Real and synthetic questions behave differently (D-015).
_GROUPS: dict[str, Callable[[Result], bool]] = {
    "all": lambda r: True,
    "real": lambda r: r["subset"] != "synthetic",
    "synthetic": lambda r: r["subset"] == "synthetic",
}


def paired_changes(base: Sequence[Result], other: Sequence[Result], metric: str) -> dict[str, int]:
    """Question by question: how often `other` scored higher, lower or the same as `base`."""
    base_by_id = {r["question_id"]: r["metrics"][metric] for r in base}
    counts = {"better": 0, "worse": 0, "same": 0}
    for result in other:
        before, after = base_by_id[result["question_id"]], result["metrics"][metric]
        counts["better" if after > before else "worse" if after < before else "same"] += 1
    return counts


def write_report(run_dirs: Sequence[Path], path: Path = REPORT_PATH) -> Path:
    """The first run is the baseline; later runs on the same split are compared with it."""
    configs = [load_config(d) for d in run_dirs]
    lines = [
        "# Retrieval: BM25 baseline",
        "",
        "Generated by `srag report-retrieval` from the run records below (D-018). Runs are",
        "git-ignored; each can be reproduced with `srag eval-retrieval` at its commit.",
        "",
        "## Runs",
        "",
        "| Run | Split | Questions | Stemming | Commit | Uncommitted changes |",
        "|---|---|---:|---|---|---|",
    ]
    for c in configs:
        commit = (c["git"]["commit"] or "unknown")[:7]
        lines.append(
            f"| `{c['run_id']}` | {c['split']} | {c['n_questions']} | "
            f"{'on' if c['tokenizer']['stem'] else 'off'} | `{commit}` | "
            f"{'yes' if c['git']['dirty'] else 'no'} |"
        )
    for run_dir, c in zip(run_dirs, configs, strict=True):
        lines += ["", f"## `{c['run_id']}`", "", format_summary(load_summary(run_dir))]

    base_dir, base_config = run_dirs[0], configs[0]
    base_results = load_results(base_dir)
    for run_dir, c in zip(run_dirs[1:], configs[1:], strict=True):
        if c["split"] != base_config["split"]:
            continue
        lines += _comparison(base_config, base_results, c, load_results(run_dir))

    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return path


def _comparison(
    base_config: dict[str, Any],
    base_results: Sequence[Result],
    other_config: dict[str, Any],
    other_results: Sequence[Result],
) -> list[str]:
    lines = [
        "",
        f"## Paired: `{other_config['run_id']}` vs `{base_config['run_id']}`",
        "",
        "Same questions in both runs. Better / worse / same counts the questions where the",
        "second run scored higher, lower or equal.",
        "",
        "| Group | Metric | Better | Worse | Same |",
        "|---|---|---:|---:|---:|",
    ]
    for group, keep in _GROUPS.items():
        base = [r for r in base_results if keep(r)]
        other = [r for r in other_results if keep(r)]
        if not other:
            continue
        for metric in COMPARED_METRICS:
            n = paired_changes(base, other, metric)
            lines.append(f"| {group} | {metric} | {n['better']} | {n['worse']} | {n['same']} |")
    return lines
