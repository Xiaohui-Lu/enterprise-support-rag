"""Corpus statistics and data checks, written to reports/corpus_stats.md.

Token counts use tiktoken's o200k_base encoding as an approximation for planning.
Claude's tokenizer differs, and cost tracking will use the token usage the API reports.
"""

from __future__ import annotations

import re
import statistics
from collections import Counter
from collections.abc import Callable, Mapping, Sequence
from pathlib import Path

from support_rag import config
from support_rag.records import Article, Question
from support_rag.wixqa import QA_SUBSETS, load_articles, load_questions

TokenCounter = Callable[[str], int]

REAL_SUBSETS = ("expertwritten", "simulated")
_HEADING = re.compile(r"<h[2-4][\s>]", re.IGNORECASE)


def tiktoken_counter(encoding: str = "o200k_base") -> TokenCounter:
    import tiktoken

    enc = tiktoken.get_encoding(encoding)
    return lambda text: len(enc.encode(text, disallowed_special=()))


def describe(values: Sequence[int]) -> list[float]:
    """min, median, mean, p90, p99, max"""
    pct = statistics.quantiles(values, n=100, method="inclusive")
    return [
        min(values),
        statistics.median(values),
        statistics.fmean(values),
        pct[89],
        pct[98],
        max(values),
    ]


def _fmt(value: object) -> str:
    if isinstance(value, float):
        return f"{value:,.0f}"
    if isinstance(value, int):
        return f"{value:,}"
    return str(value)


def _table(headers: Sequence[str], rows: Sequence[Sequence[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(_fmt(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def build_report(
    articles: Sequence[Article],
    questions: Mapping[str, Sequence[Question]],
    count_tokens: TokenCounter,
) -> str:
    kb = {a.id: a for a in articles}
    tokens = [count_tokens(a.contents) for a in articles]
    chars = [len(a.contents) for a in articles]
    headings = [len(_HEADING.findall(a.html)) for a in articles]
    real = [q for s in REAL_SUBSETS for q in questions[s]]
    with_feature_request = sum(
        any(g in kb and kb[g].article_type == "feature_request" for g in q.gold_ids) for q in real
    )

    out = [
        "# Corpus statistics",
        "",
        f"Generated by `srag stats` from WixQA revision `{config.DATASET_REVISION[:7]}`. "
        "Token counts use tiktoken `o200k_base` as an approximation; Claude's tokenizer "
        "differs, and cost tracking uses the token usage the API reports.",
        "",
        "## Knowledge base",
        "",
        _table(["Article type", "Count"], Counter(a.article_type for a in articles).most_common()),
        "",
        _table(
            ["", "Min", "Median", "Mean", "p90", "p99", "Max"],
            [["Characters", *describe(chars)], ["Tokens", *describe(tokens)]],
        ),
        "",
        f"- Articles: {len(articles):,}. Total tokens: {sum(tokens):,}.",
        f"- Over 2,000 tokens: {sum(t > 2000 for t in tokens):,}. "
        f"Over 8,000 tokens: {sum(t > 8000 for t in tokens):,}.",
        f"- With two or more section headings (h2 to h4) in the HTML: "
        f"{sum(h >= 2 for h in headings):,}.",
        "",
        "## Questions",
        "",
    ]

    max_gold = max(len(q.gold_ids) for s in QA_SUBSETS for q in questions[s])
    rows = []
    for subset in QA_SUBSETS:
        qs = questions[subset]
        per_question = Counter(len(q.gold_ids) for q in qs)
        rows.append(
            [
                subset,
                len(qs),
                *(per_question.get(k, 0) for k in range(1, max_gold + 1)),
                statistics.median([count_tokens(q.question) for q in qs]),
                statistics.median([count_tokens(q.answer) for q in qs]),
            ]
        )
    headers = [
        "Subset",
        "Questions",
        *(f"{k} gold" for k in range(1, max_gold + 1)),
        "Median question tokens",
        "Median answer tokens",
    ]
    out += [
        _table(headers, rows),
        "",
        "## Gold articles of the real questions",
        "",
        "Which kind of KB article answers the expert-written and simulated questions.",
        "",
        _table(
            ["Article type", "Gold references"],
            Counter(kb[g].article_type for q in real for g in q.gold_ids if g in kb).most_common(),
        ),
        "",
        "- Real questions with at least one feature request among their gold articles: "
        f"{with_feature_request:,} of {len(real):,}.",
        "",
        "## Data checks",
        "",
        "Every count should be 0 unless noted.",
        "",
    ]

    checks: list[list[object]] = [
        [
            "Duplicate article IDs in the KB",
            sum(c > 1 for c in Counter(a.id for a in articles).values()),
        ],
        ["Articles with empty text", sum(not a.contents.strip() for a in articles)],
    ]
    for subset in QA_SUBSETS:
        qs = questions[subset]
        texts = Counter(q.question.strip().lower() for q in qs)
        checks.append(
            [
                f"{subset}: gold IDs missing from the KB",
                sum(g not in kb for q in qs for g in q.gold_ids),
            ]
        )
        checks.append([f"{subset}: repeated questions", sum(c - 1 for c in texts.values())])
    ew = {q.question.strip().lower() for q in questions["expertwritten"]}
    sim = {q.question.strip().lower() for q in questions["simulated"]}
    checks.append(["Questions in both expertwritten and simulated", len(ew & sim)])
    covered = {g for q in questions["synthetic"] for g in q.gold_ids}
    uncovered = sum(a.id not in covered for a in articles)
    checks.append(["KB articles with no synthetic question (expected: few)", uncovered])
    out += [_table(["Check", "Count"], checks), ""]
    return "\n".join(out)


def write_report(
    raw_dir: Path = config.RAW_DIR,
    reports_dir: Path = config.REPORTS_DIR,
    count_tokens: TokenCounter | None = None,
) -> Path:
    articles = load_articles(raw_dir)
    questions = {subset: load_questions(subset, raw_dir) for subset in QA_SUBSETS}
    report = build_report(articles, questions, count_tokens or tiktoken_counter())
    reports_dir.mkdir(parents=True, exist_ok=True)
    path = reports_dir / "corpus_stats.md"
    path.write_text(report, encoding="utf-8")
    return path
